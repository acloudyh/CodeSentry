CREATE TABLE IF NOT EXISTS scan_ai_review_job (
    id BIGINT NOT NULL AUTO_INCREMENT,
    scan_run_id BIGINT NOT NULL,
    provider VARCHAR(64) NOT NULL,
    model VARCHAR(255) NOT NULL,
    status VARCHAR(24) NOT NULL,
    total_findings INT NOT NULL DEFAULT 0,
    completed_findings INT NOT NULL DEFAULT 0,
    failed_findings INT NOT NULL DEFAULT 0,
    error_message TEXT NULL,
    created_at DATETIME(3) NOT NULL,
    started_at DATETIME(3) NULL,
    finished_at DATETIME(3) NULL,
    PRIMARY KEY (id),
    KEY idx_ai_review_job_run (scan_run_id, created_at),
    CONSTRAINT fk_ai_review_job_run FOREIGN KEY (scan_run_id) REFERENCES scan_run (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS scan_ai_review (
    id BIGINT NOT NULL AUTO_INCREMENT,
    project_id BIGINT NOT NULL,
    scan_run_id BIGINT NOT NULL,
    finding_id BIGINT NOT NULL,
    review_job_id BIGINT NULL,
    review_round VARCHAR(24) NOT NULL,
    provider VARCHAR(64) NOT NULL,
    model VARCHAR(255) NOT NULL,
    verdict VARCHAR(32) NOT NULL,
    confidence DECIMAL(5,4) NOT NULL DEFAULT 0,
    reason TEXT NULL,
    evidence_lines TEXT NULL,
    missing_evidence TEXT NULL,
    recommendation TEXT NULL,
    input_hash CHAR(64) NOT NULL,
    prompt_version VARCHAR(128) NOT NULL,
    status VARCHAR(24) NOT NULL,
    error_message TEXT NULL,
    created_at DATETIME(3) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_ai_review_finding (finding_id, created_at),
    KEY idx_ai_review_run (scan_run_id, created_at),
    KEY idx_ai_review_job (review_job_id),
    CONSTRAINT fk_ai_review_project FOREIGN KEY (project_id) REFERENCES scan_project (id),
    CONSTRAINT fk_ai_review_run FOREIGN KEY (scan_run_id) REFERENCES scan_run (id),
    CONSTRAINT fk_ai_review_finding FOREIGN KEY (finding_id) REFERENCES scan_finding (id),
    CONSTRAINT fk_ai_review_job FOREIGN KEY (review_job_id) REFERENCES scan_ai_review_job (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
